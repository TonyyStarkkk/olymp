// Authoring helpers generate ordinary beginner Python, using only print/if/elif.
const printRows = (digit: string) =>
  digitPatterns[digit]
    .split("\n")
    .map((row) => `    print("${row}")`)
    .join("\n");
const fontSolution = (digits: string[]) =>
  "d = int(input())\n" +
  digits
    .map(
      (digit, i) =>
        `${i === 0 ? "if" : "elif"} d == ${digit}:\n${printRows(digit)}`,
    )
    .join("\n");
const cases = (pairs: [string, string][]): TestCase[] =>
  pairs.map(([input, expected]) => ({ input, expected }));

